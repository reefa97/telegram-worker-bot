-- ========================================
-- Object Classifications
-- ========================================
-- A classification is a "type of object Reefa serves" — office, clinic,
-- school, parking, hotel, etc. Each classification carries a cleaning
-- standard (checklist) so workers know exactly what to do, and clients
-- can see what's expected on their object.
--
-- cleaning_standard is JSONB: array of { section: text, items: text[] }
-- so admins can edit both the section structure and the items freely.
-- ========================================

CREATE TABLE IF NOT EXISTS object_classifications (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  category TEXT NOT NULL,            -- 'office' | 'residential' | 'specialist' | 'post_work' | 'event'
  slug TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,                -- "Офис", "Медицина"...
  icon TEXT,                         -- emoji or short string
  description TEXT,
  cleaning_standard JSONB NOT NULL DEFAULT '[]'::jsonb,
  sort_order INT DEFAULT 0,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_object_classifications_category
  ON object_classifications(category, sort_order);

-- FK on cleaning_objects
ALTER TABLE cleaning_objects
  ADD COLUMN IF NOT EXISTS classification_id UUID
  REFERENCES object_classifications(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_cleaning_objects_classification
  ON cleaning_objects(classification_id);

-- ---- RLS ----
ALTER TABLE object_classifications ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "classifications read all authenticated" ON object_classifications;
DROP POLICY IF EXISTS "classifications admin write"            ON object_classifications;

CREATE POLICY "classifications read all authenticated"
  ON object_classifications FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "classifications admin write"
  ON object_classifications FOR ALL
  TO authenticated
  USING (is_admin())
  WITH CHECK (is_admin());

